"""
Run from your website folder:   python convert_pages.py
Converts every .html page (except header.html / footer.html) to:
  - plain static HTML (removes the Next.js/React scripts that fight with includes)
  - fixes the file:///C:/... links
  - replaces header & footer with <div id="site-header"> / <div id="site-footer">
  - adds favicon, fixes canonical/description, loads /includes.js
Originals are saved in the _backup folder first.
"""
import re, sys, shutil, pathlib

DOMAIN = "https://www.shreeprannathoil.com.np"
DESC = ("Shree Prannath Oil Mill, Ratnanagar, Chitwan - pure cold-pressed mustard oil, "
        "oil pressing services and Nepal-wide delivery.")
root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
backup = root / "_backup"; backup.mkdir(exist_ok=True)
SKIP = {"header.html", "footer.html"}
FLAGS = re.S | re.I

for f in sorted(root.glob("*.html")):
    if f.name in SKIP:
        continue
    s = f.read_text(encoding="utf-8-sig")
    shutil.copy(f, backup / f.name)

    # 1. links
    s = re.sub(r'file:///C:/Users/[^"\']*?SPO_chatgpt_main_folder%20\(1\)/', '/', s)
    s = s.replace('href="/index.html"', 'href="/"')
    s = s.replace('file:///C:/services', '/services.html')
    for p in ("privacy", "terms", "shipping"):
        s = s.replace(f'file:///C:/{p}', '#')
    s = re.sub(r'(href|src)="\./', r'\1="/', s)

    # 2. remove saved-page comment, React attrs, all scripts except JSON-LD, preloads
    s = re.sub(r'<!-- saved from url.*?-->', '', s, flags=FLAGS)
    s = re.sub(r'\sdata-react-source="[^"]*"', '', s)
    s = re.sub(r'<script(?![^>]*application/ld\+json)[^>]*>.*?</script>', '', s, flags=FLAGS)
    s = re.sub(r'<link[^>]+rel="preload"[^>]*>', '', s, flags=FLAGS)
    s = re.sub(r'<meta name="next-size-adjust"[^>]*>', '', s)

    # 3. stylesheet -> /site.css
    s = re.sub(r'<link rel="stylesheet" href="[^"]*8ebb6d4b[^"]*"[^>]*>',
               '<link rel="stylesheet" href="/site.css">', s)

    # 4. header / footer -> placeholders
    s = re.sub(r'<header\b.*?</header>', '<div id="site-header" style="display:contents"></div>', s, count=1, flags=FLAGS)
    s = re.sub(r'<footer\b.*?</footer>', '<div id="site-footer"></div>', s, count=1, flags=FLAGS)

    # 5. SEO fixes
    s = s.replace('shreeprannatoil', 'shreeprannathoil')
    url = DOMAIN + ("/" if f.name == "index.html" else "/" + f.name)
    s = re.sub(r'<link rel="canonical"[^>]*>', f'<link rel="canonical" href="{url}">', s)
    s = re.sub(r'<link rel="alternate" hreflang[^>]*>\s*', '', s)
    s = re.sub(r'(<meta property="og:url" content=")[^"]*', rf'\g<1>{url}', s)
    s = s.replace('content="Generated by create next app"', f'content="{DESC}"')

    # 6. favicon + includes
    if 'rel="icon"' not in s:
        s = s.replace('</head>', '<link rel="icon" href="/favicon.svg" type="image/svg+xml">\n'
                                 '</head>', 1)
    if '/includes.js' not in s:
        s = s.replace('</body>', '<script src="/includes.js" defer></script>\n</body>', 1)

    f.write_text(s, encoding="utf-8")
    print("converted", f.name)
print("Done. Originals are in", backup)
